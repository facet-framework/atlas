// Shared synthetic corpus fixtures used by the HTTP reader's integration tests.
// @facet-ignore-file

package server

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/facet-framework/core/registry"
)

const quickAdd = `schema_version: "0.1"
id: tasks/create/quick-add
lifecycle: active
intent:
  summary: Adds a task from one line of input.
`

func project(t *testing.T, files map[string]string) facet.Registry {
	t.Helper()
	root := t.TempDir()
	for name, body := range files {
		path := filepath.Join(root, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return facet.Open(root)
}

func keys(m map[string]string) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	return out
}

func itoa(n int) string {
	if n == 0 {
		return "0"
	}
	var digits []byte
	for n > 0 {
		digits = append([]byte{byte('0' + n%10)}, digits...)
		n /= 10
	}
	return string(digits)
}

func mustWriteCorpus(t *testing.T, path, body string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}
